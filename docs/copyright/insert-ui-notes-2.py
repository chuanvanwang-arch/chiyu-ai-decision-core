def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    src = MANUAL.read_text(encoding="utf-8")
    counter = {"n": 0}

    def repl(m: re.Match) -> str:
        idx = counter["n"]
        counter["n"] += 1
        if idx >= len(POINTS):
            return m.group(0)
        key = f"<!-- ui2:{idx + 1} -->"
        if key in src:
            return m.group(0)
        return m.group(0) + f"\n{key}\n{POINTS[idx]}"

    new = FIG_RE.sub(repl, src)
    print(f"门户界面图 {counter['n']} 张，要点文案 {len(POINTS)} 条")
    if args.dry_run:
        print("（dry-run，未写盘）")
        return 0
    MANUAL.write_text(new, encoding="utf-8")
    print(f"已写回：{MANUAL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
