def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    src = MANUAL.read_text(encoding="utf-8")
    counter = {"n": 0}

    def repl(m: re.Match) -> str:
        idx = counter["n"]
        counter["n"] += 1
        if idx >= len(NOTES):
            print(f"  ! 第 {idx + 1} 张门户界面图无对应说明，已跳过：{m.group('name')}")
            return m.group(0)
        key = f"<!-- ui:{idx + 1} -->"
        if key in src:
            return m.group(0)
        note = NOTES[idx]
        return f"{key}\n{note}\n\n" + m.group(0)

    new = FIG_RE.sub(repl, src)
    total = counter["n"]
    print(f"门户界面图共 {total} 张，说明文案 {len(NOTES)} 条")
    if args.dry_run:
        print("（dry-run，未写盘）")
        return 0
    MANUAL.write_text(new, encoding="utf-8")
    print(f"已写回：{MANUAL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
