SEC_RE = re.compile(r"<h2>(E\.\d+)[^<]*</h2>")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    src = MANUAL.read_text(encoding="utf-8")
    inserted = 0

    for sec, note in NOTES.items():
        key = f"<!-- sect:{sec} -->"
        if key in src:
            continue
        # 定位该节正文区间：[h2 起点, 下一个 h2 或 h1 起点)
        m = re.search(rf"<h2>{sec}[^<]*</h2>", src)
        if not m:
            print(f"  ! 未找到小节 {sec}")
            continue
        nxt = re.search(r"<h[12][ >]", src[m.end():])
        end = m.end() + nxt.start() if nxt else len(src)
        block = f"{key}\n{note}\n\n"
        src = src[:end] + block + src[end:]
        inserted += 1

    print(f"本次插入节末要点：{inserted} 段（共 {len(NOTES)} 段）")
    if args.dry_run:
        print("（dry-run，未写盘）")
        return 0
    MANUAL.write_text(src, encoding="utf-8")
    print(f"已写回：{MANUAL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
