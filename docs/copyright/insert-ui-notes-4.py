#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""为门户界面图补「相关配置项说明」，使图页文字行数达标。

幂等：以 `<!-- ui4:N -->` 注释为标记。

用法：
    python docs/copyright/insert-ui-notes-4.py [--dry-run]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MANUAL = ROOT / "user-manual.html"

FIG_RE = re.compile(
    r"[ \t]*<figure>\s*<img\s+src=\"screenshots/(?P<name>A[^\"]+)\.png\"[^>]*>\s*"
    r"<figcaption>(?P<cap>.*?)</figcaption>\s*</figure>",
    re.S,
)

CFG: list[str] = [
    """<p><b>相关配置项。</b>方向列表由租户画像的配置项决定，配置中声明几个方向，
页面即呈现几项；方向名称建议使用中性表述，不写具体行业名词，以便同一套界面跨领域复用。</p>""",
    """<p><b>相关配置项。</b>工作流与其难度分级来自工作流配置；如需增加新的工作流，
在配置中追加条目即可，分级字段决定其在界面上的排列位置，无需改动前端代码。</p>""",
    """<p><b>相关配置项。</b>工作模式及其插件组合来自模式预设与插件注册表两处配置：
模式预设定义模式的名称与默认项，插件注册表定义每个插件在各模式下的启用状态。</p>""",
    """<p><b>相关配置项。</b>确认页提交的三项选择会写入会话初始上下文，
后续所有轮次的处理都在该上下文中进行；会话上下文在会话存续期内保持不变。</p>""",
    """<p><b>相关配置项。</b>输入区的功能开关与模型选择器对应请求级的执行参数，
可逐次调整而不影响会话级配置；会话级配置（方向、工作流、模式）只在引导阶段设定。</p>""",
    """<p><b>相关配置项。</b>能力面板展示的内容由登记表驱动：插件来自插件注册表，
原生工具来自决策层工具清单，评分细则来自评分量规，三者均随版本发布同步更新。</p>""",
    """<p><b>相关配置项。</b>工具调用的可用范围取决于当前工作模式所启用的插件组合；
评分取值取决于评分量规与本次请求给出的评分输入。调整配置后重新发起决策即可观察到差异。</p>""",
    """<p><b>相关配置项。</b>会话记录保存在会话存储中，会话之间的方向、工作流与模式互不影响；
如需按租户或按用户隔离会话，应在接入时按存储的隔离粒度进行配置。</p>""",
    """<p><b>相关配置项。</b>插件的启用状态是模式配置的结果，而非逐次手工开关；
如需长期改变某插件的启用范围，应调整模式预设或注册表，而不是在会话中临时改动。</p>""",
    """<p><b>相关配置项。</b>评分细则中的九个维度为固定集合，含义由评分量规定义；
各维度的权重可通过画像注入调整，但维度集合本身属于契约，不随配置变化。</p>""",
    """<p><b>相关配置项。</b>阶段轨迹的内容由阶段契约决定，各阶段的输出字段为契约字段；
契约版本变更时阶段轨迹的字段可能增加，接入方应按字段名取值而非按位置取值。</p>""",
    """<p><b>相关配置项。</b>导出的页面描述被保存在页面存储中，与产生它的会话相互独立；
即使原会话被关闭，已导出的页面仍然可访问，便于归档与交付。</p>""",
    """<p><b>相关配置项。</b>模型端点按层配置，各层的地址与凭据相互独立；
某一层未配置时该层不可用，软件按既定顺序回落到可用层，并在处理轨迹中标注实际采用的层。</p>""",
    """<p><b>相关配置项。</b>引导页呈现的分级参数（工作流、难度）均来自配置，
修改配置即可调整引导内容；引导步骤本身为固定四步，属于交互契约，不随配置增减。</p>""",
    """<p><b>相关配置项。</b>模式与插件的对应关系在《附录 C 默认参数一览》中集中列出，
接入方在评估模式差异时可先查阅该表，再到界面上核对实际呈现，两者应完全一致。</p>""",
    """<p><b>相关配置项。</b>工作台的会话级配置在引导阶段确定，请求级参数在输入区逐次确定，
两级配置分离的设计使「同一个会话内多次尝试不同执行方式」成为可能，
而不必为每次尝试重新建立会话。</p>""",
]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    src = MANUAL.read_text(encoding="utf-8")
    counter = {"n": 0}

    def repl(m: re.Match) -> str:
        idx = counter["n"]
        counter["n"] += 1
        if idx >= len(CFG):
            return m.group(0)
        key = f"<!-- ui4:{idx + 1} -->"
        if key in src:
            return m.group(0)
        return m.group(0) + f"\n{key}\n{CFG[idx]}"

    new = FIG_RE.sub(repl, src)
    print(f"门户界面图 {counter['n']} 张，配置说明 {len(CFG)} 条")
    if args.dry_run:
        print("（dry-run，未写盘）")
        return 0
    MANUAL.write_text(new, encoding="utf-8")
    print(f"已写回：{MANUAL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
