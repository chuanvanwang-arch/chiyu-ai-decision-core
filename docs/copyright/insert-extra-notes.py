def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    src = MANUAL.read_text(encoding="utf-8")
    ok, miss, skip = 0, 0, 0

    for idx, anchor, content in PATCHES:
        key = f"<!-- extra:{idx} -->"
        if key in src:
            skip += 1
            continue
        if anchor not in src:
            print(f"  ! 锚点未命中（#{idx}）：{anchor[:40]}…")
            miss += 1
            continue
        # 插到锚点所在元素的结束标签之后
        pos = src.index(anchor) + len(anchor)
        # 若锚点是 <tr>，须跳过该行剩余部分与所在表格
        if anchor.startswith("<tr>") or anchor.startswith("<td>"):
            table_end = src.index("</table>", pos) + len("</table>")
            pos = table_end
        block = f"\n{key}{content}"
        src = src[:pos] + block + src[pos:]
        ok += 1

    print(f"插入成功 {ok} 段　|　锚点未命中 {miss} 段　|　已存在跳过 {skip} 段")
    if args.dry_run:
        print("（dry-run，未写盘）")
        return 0
    MANUAL.write_text(src, encoding="utf-8")
    print(f"已写回：{MANUAL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
